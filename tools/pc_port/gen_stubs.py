#!/usr/bin/env python3
"""Generate C stubs for library functions the PC build does not provide
(online services, local wireless, GBA slot, microphone, anti-piracy...).

Each stub re-uses the exact declaration text found in the sources (so it
matches every caller), logs its first call and returns a neutral value.
Return values that must keep the game moving are listed in OVERRIDES.

Usage (libclang Python package required, e.g. build-pc/venv):
    python tools/pc_port/gen_stubs.py OUT_DIR SYMBOL_LIST [--gen-dir build-clang/generated]
"""
import argparse
import collections
import pathlib
import re
import sys

import clang.cindex as ci

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from asm_data_to_c import ROOT, Types  # noqa: E402

# Return expressions that differ from "zero" because callers wait on them.
OVERRIDES = {
    "SND_IsFinishedCommandTag": "1",         # sound commands complete at once
    "SND_RecvCommandReply": "NULL",
    "OS_SpinWait": None,
    "DSProt_DetectNotDummy": "1",         # anti-piracy: report a genuine cartridge
    "DSProt_DetectNotEmulator": "1",
    "DSProt_DetectNotFlashcart": "1",
    "DSProt_DetectDummy": "0",
    "DSProt_DetectEmulator": "0",
    "DSProt_DetectFlashcart": "0",
}


def decl_text(cursor):
    ext = cursor.extent
    path = pathlib.Path(ext.start.file.name)
    text = path.read_bytes()
    src = text[ext.start.offset:ext.end.offset].decode("utf-8", "replace")
    src = re.sub(r"\s*\{.*$", "", src, flags=re.S)      # definition body, if any
    src = re.sub(r"^\s*(extern|static|inline|static inline)\s+", "", src)
    return " ".join(src.split()), path


def generic_return(t):
    """(C return type with the same size/class, zero value)."""
    t = t.get_canonical()
    if t.kind == ci.TypeKind.VOID:
        return "void", None
    if t.kind == ci.TypeKind.POINTER:
        return "void *", "NULL"
    if t.kind == ci.TypeKind.FLOAT:
        return "float", "0.0f"
    if t.kind == ci.TypeKind.DOUBLE:
        return "double", "0.0"
    if t.kind == ci.TypeKind.RECORD:
        return f"pcstub_ret{t.get_size()}", None
    return ("long long", "0") if t.get_size() == 8 else ("int", "0")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("symbols")
    ap.add_argument("--gen-dir", default=str(ROOT / "build-clang" / "generated"))
    args = ap.parse_args()

    names = [l.strip() for l in open(args.symbols, encoding="utf-8") if l.strip()]
    types = Types(args.gen_dir)
    found, missing = {}, []
    for n in names:
        if types.ident_files is None:
            types.ident_files = types._ident_index()
        cur = None
        for f in sorted(types.ident_files.get(n, ()), key=lambda p: (p.suffix != ".h", str(p))):
            tu = types._parse(f)
            for c in tu.cursor.get_children():
                if c.kind == ci.CursorKind.FUNCTION_DECL and c.spelling == n:
                    cur = c
                    break
            if cur:
                break
        if cur is None:
            missing.append(n)
        else:
            found[n] = cur

    # Stubs use a generic signature, `RET name()` (unspecified arguments), and
    # include no game header: only the return type's size/class matters to the
    # caller, and declarations that are not self-contained (types local to a
    # .c file, C++ lobby code...) cannot cause build errors.
    by_origin = collections.defaultdict(list)
    for n, c in found.items():
        text, path = decl_text(c)
        by_origin[path].append((n, text, c.result_type))

    out = pathlib.Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for path, entries in by_origin.items():
        rel = path.resolve().relative_to(ROOT).as_posix()
        stem = re.sub(r"\W+", "_", rel)
        lines = [f"/* Generated by tools/pc_port/gen_stubs.py - offline stubs for functions declared in {rel}.",
                 " * The original declaration is kept in a comment above each stub. */",
                 "#include <stddef.h>", "#include <string.h>", "",
                 "void pc_stub_called(const char *name);", ""]
        structs = set()
        for n, text, rt in sorted(entries):
            ret_type, ret_val = generic_return(rt)
            if ret_type.startswith("pcstub_ret"):
                structs.add(rt.get_canonical().get_size())
            ret_val = OVERRIDES.get(n, ret_val)
            body = [f'    pc_stub_called("{n}");']
            if ret_type.startswith("pcstub_ret"):
                body += [f"    {ret_type} r;", "    memset(&r, 0, sizeof r);", "    return r;"]
            elif ret_type != "void":
                body.append(f"    return {ret_val};")
            lines.append(f"/* {text}; */\n{ret_type} {n}() {{\n" + "\n".join(body) + "\n}\n")
        for size in sorted(structs):
            lines.insert(6, f"typedef struct {{ unsigned char b[{size}]; }} pcstub_ret{size};")
        (out / f"stub_{stem}.c").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(found)} stubs in {len(by_origin)} files; {len(missing)} without a C declaration")
    if missing:
        print("  no declaration:", " ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
