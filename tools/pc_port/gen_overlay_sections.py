#!/usr/bin/env python3
"""Give every overlay's variables their own linker section (PC build, Clang).

On the DS, loading an overlay copies its .data from the ROM and zeroes its
.bss, so its global and static variables start fresh on every load. On PC all
overlays are linked into the executable, so the PC layer snapshots each
overlay's variables at start-up and restores them when the game loads the
overlay again (src/platform_pc/nitro/fs_nitro_pc.c).

For that, the variables of overlay N must be contiguous:
  - every source of overlay N is compiled with
        -fno-zero-initialized-in-bss  (zero-initialised variables go to .data)
        -include ovl_NNN.h            (#pragma clang section data=".data$ovlNNN$1")
  - begin/end markers live in ".data$ovlNNN$0" and ".data$ovlNNN$2"; the
    linker sorts grouped COFF sections by name, so [begin, end] spans them.

The same scheme gathers every other variable of the game (main program,
data converted from assembly, offline stubs, the game-facing half of the
Nitro layer) in ".data$main$1", which a soft reset (OS_ResetSystem) restores.
CMake applies main.h to those sources; an overlay's own header comes later
on the command line and wins.

Outputs (configure time, from main.lsf):
  OUT_DIR/pc_ovl/main.h               the main-program pragma header
  OUT_DIR/pc_ovl/ovl_NNN.h            the per-overlay pragma headers
  OUT_DIR/pc_overlay_sections.c       markers, gPcMainData, gPcOverlayData[]
  OUT_DIR/pc_overlay_sources.cmake    set_source_files_properties() calls

Usage: python tools/pc_port/gen_overlay_sections.py OUT_DIR
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASM_DATA = ROOT / "src/platform_pc/generated/asm_data"


def write_if_changed(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8", newline="\n")


def sources_for(obj):
    """Host C sources built from a main.lsf object path."""
    stem = obj[:-2]  # strip .o
    if "/asm/" in "/" + stem:
        name = stem.rsplit("/", 1)[1]
        return [p for p in (ASM_DATA / f"{name}_raw.c", ASM_DATA / f"{name}_typed.c") if p.exists()]
    c = ROOT / (stem + ".c")
    return [c] if c.exists() else []


def main():
    out = pathlib.Path(sys.argv[1])
    text = (ROOT / "main.lsf").read_text(encoding="utf-8")
    blocks = re.findall(r"^(Static|Autoload|Overlay)\s+(\w+)\s*\{(.*?)\}", text, re.M | re.S)
    owner = {}       # source path -> overlay index, or None for main/autoloads
    overlays = []    # names, in overlay-ID order
    conflicts = []
    for kind, name, body in blocks:
        idx = None
        if kind == "Overlay":
            idx = len(overlays)
            overlays.append(name)
        for obj in re.findall(r"^\s*Object\s+(\S+\.o)\b", body, re.M):
            for src in sources_for(obj):
                if src in owner and owner[src] != idx:
                    conflicts.append(src)
                owner.setdefault(src, idx)
    # A source linked twice (main + overlay, or two overlays) keeps its first
    # owner but is not reset: its variables would belong to two overlays.
    for src in conflicts:
        owner[src] = None

    for i, _ in enumerate(overlays):
        write_if_changed(out / f"pc_ovl/ovl_{i:03d}.h",
                         "/* Generated by tools/pc_port/gen_overlay_sections.py - do not edit. */\n"
                         f'#pragma clang section data=".data$ovl{i:03d}$1"\n')

    write_if_changed(out / "pc_ovl/main.h",
                     "/* Generated by tools/pc_port/gen_overlay_sections.py - do not edit. */\n"
                     '#pragma clang section data=".data$main$1"\n')

    c = ["/* Generated by tools/pc_port/gen_overlay_sections.py from main.lsf - do not edit. */",
         '#include "pc_overlay_sections.h"', "",
         '__attribute__((section(".data$main$0"), used, aligned(16))) char pcmain_begin = 1;',
         '__attribute__((section(".data$main$2"), used)) char pcmain_end = 1;',
         "const PcOverlayData gPcMainData = { &pcmain_begin, &pcmain_end + 1 };", ""]
    for i, _ in enumerate(overlays):
        c.append(f'__attribute__((section(".data$ovl{i:03d}$0"), used, aligned(16))) char pcovl{i}_begin = 1;')
        c.append(f'__attribute__((section(".data$ovl{i:03d}$2"), used)) char pcovl{i}_end = 1;')
    c += ["", f"const PcOverlayData gPcOverlayData[{len(overlays)}] = {{"]
    c += [f"    {{ &pcovl{i}_begin, &pcovl{i}_end + 1 }}, /* {n} */" for i, n in enumerate(overlays)]
    c += ["};", ""]
    write_if_changed(out / "pc_overlay_sections.c", "\n".join(c))

    cm = ["# Generated by tools/pc_port/gen_overlay_sections.py - do not edit."]
    counts = [0] * len(overlays)
    for src, idx in sorted(owner.items(), key=lambda kv: str(kv[0])):
        if idx is None:
            continue
        counts[idx] += 1
        hdr = (out / f"pc_ovl/ovl_{idx:03d}.h").as_posix()
        cm.append(f'set_property(SOURCE "{src.as_posix()}" APPEND PROPERTY COMPILE_OPTIONS '
                  f'"-fno-zero-initialized-in-bss" "-include" "{hdr}")')
    write_if_changed(out / "pc_overlay_sources.cmake", "\n".join(cm) + "\n")
    print(f"{len(overlays)} overlays, {sum(counts)} sources assigned, "
          f"{len(conflicts)} shared sources left in main")


if __name__ == "__main__":
    main()
