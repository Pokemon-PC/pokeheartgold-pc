#ifndef POKEHEARTGOLD_POKEDEX_LANGUAGE_H
#define POKEHEARTGOLD_POKEDEX_LANGUAGE_H

#include "global.h"

#include "config.h"

#define DEX_LANGUAGE_FLAG_JAPANESE 0
#define DEX_LANGUAGE_FLAG_ENGLISH  1
#define DEX_LANGUAGE_FLAG_FRENCH   2
#define DEX_LANGUAGE_FLAG_GERMAN   3
#define DEX_LANGUAGE_FLAG_ITALIAN  4
#define DEX_LANGUAGE_FLAG_SPANISH  5
#define DEX_LANGUAGE_FLAG_MAX      6

#ifdef PLATFORM_PC
// GAME_LANGUAGE is a run-time value on PC.
#define DEX_LANGUAGE_FLAG_NATIVE ( \
    GAME_LANGUAGE == LANGUAGE_JAPANESE ? DEX_LANGUAGE_FLAG_JAPANESE : \
    GAME_LANGUAGE == LANGUAGE_FRENCH   ? DEX_LANGUAGE_FLAG_FRENCH :   \
    GAME_LANGUAGE == LANGUAGE_GERMAN   ? DEX_LANGUAGE_FLAG_GERMAN :   \
    GAME_LANGUAGE == LANGUAGE_ITALIAN  ? DEX_LANGUAGE_FLAG_ITALIAN :  \
    GAME_LANGUAGE == LANGUAGE_SPANISH  ? DEX_LANGUAGE_FLAG_SPANISH :  \
                                         DEX_LANGUAGE_FLAG_ENGLISH)
#elif GAME_LANGUAGE == LANGUAGE_JAPANESSE
#define DEX_LANGUAGE_FLAG_NATIVE DEX_LANGUAGE_FLAG_JAPANESE
#elif GAME_LANGUAGE == LANGUAGE_ENGLISH
#define DEX_LANGUAGE_FLAG_NATIVE DEX_LANGUAGE_FLAG_ENGLISH
#elif GAME_LANGUAGE == LANGUAGE_FRENCH
#define DEX_LANGUAGE_FLAG_NATIVE DEX_LANGUAGE_FLAG_FRENCH
#elif GAME_LANGUAGE == LANGUAGE_GERMAN
#define DEX_LANGUAGE_FLAG_NATIVE DEX_LANGUAGE_FLAG_GERMAN
#elif GAME_LANGUAGE == LANGUAGE_ITALIAN
#define DEX_LANGUAGE_FLAG_NATIVE DEX_LANGUAGE_FLAG_ITALIAN
#elif GAME_LANGUAGE == LANGUAGE_SPANISH
#define DEX_LANGUAGE_FLAG_NATIVE DEX_LANGUAGE_FLAG_SPANISH
#else
#error "Unsupported language"
#endif

int LanguageToDexFlag(u32 language);
int DexFlagToLanguage(int index);

#endif // POKEHEARTGOLD_POKEDEX_LANGUAGE_H
